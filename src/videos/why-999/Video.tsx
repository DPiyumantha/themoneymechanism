/**
 * Why is it always $9.99? (Priced In) — script and sources in ./script.md.
 * Scenes are timed to public/videos/why-999/voiceover.mp3 (Gemini TTS take; word
 * timings in ./captions.json, aligned to the audio). If the voice-over is replaced,
 * re-time BEATS and the delays.
 */
import React from "react";
import { AbsoluteFill, interpolate, Sequence, staticFile } from "remotion";
import { Audio } from "@remotion/media";
import type { Caption } from "@remotion/captions";
import { linearTiming, TransitionSeries } from "@remotion/transitions";
import { slide } from "@remotion/transitions/slide";
import { sec, theme } from "../../brand";
import {
  BrandBackground,
  BrandedVideo,
  Captions,
  HookText,
  Kicker,
  ListReveal,
  Mascot,
  PriceTag,
  SafeArea,
  SourceNote,
  VersusCard,
} from "../../components";
import captionsJson from "./captions.json";

const T = theme.motion.transitionFrames;

// Beat starts (s), each just before its first word in the voice-over:
// hook+setup, meme ("It sees"), versus ("Researchers"), list ("You'll"), twist ("So"), payoff ("One cent"), end.
// Voice-over (Gemini) runs 36.65 s; the end leaves ~0.55 s of breathing room.
const BEATS = [0, 6.5, 11.7, 19.05, 26.15, 33.45, 37.2];
const len = (i: number) => sec(BEATS[i + 1]) - sec(BEATS[i]);

// Scene lengths in frames; every scene but the last gets +T for the overlapping push.
const SCENES = {
  intro: len(0) + T,
  meme: len(1) + T,
  versus: len(2) + T,
  list: len(3) + T,
  twist: len(4) + T,
  payoff: len(5),
};
const TRANSITIONS = Object.keys(SCENES).length - 1;

/** Content length without the end card. Registered in src/videos/index.ts. */
export const CONTENT_FRAMES =
  Object.values(SCENES).reduce((a, b) => a + b, 0) - TRANSITIONS * T;

// Word timings aligned to the voice-over (numbers written the way the screen shows them).
const captions: Caption[] = captionsJson;

const push = () => (
  <TransitionSeries.Transition
    presentation={slide({ direction: "from-right" })}
    timing={linearTiming({ durationInFrames: T })}
  />
);

/** One sound effect, starting `at` frames into its scene (public/sfx, generated by scripts/audio/sfx.mjs). */
const Sfx: React.FC<{ name: string; at: number; volume?: number }> = ({ name, at, volume = 0.5 }) => (
  <Sequence from={at} layout="none">
    <Audio src={staticFile(`sfx/${name}.mp3`)} volume={volume} />
  </Sequence>
);

/** Music bed: 0.12 under the voice, 15-frame fade in, 30-frame fade out before the end card. */
const musicVolume = (f: number) =>
  interpolate(f, [0, 15, CONTENT_FRAMES - 30, CONTENT_FRAMES], [0, 0.12, 0.12, 0], {
    extrapolateLeft: "clamp",
    extrapolateRight: "clamp",
  });

/** Frame (scene-relative) where the hook question hands over to "left to right". */
const SETUP_AT = sec(3.35);

export const Why999: React.FC = () => (
  <BrandedVideo contentFrames={CONTENT_FRAMES}>
    <BrandBackground />
    <TransitionSeries>
      {/* 1–2. Hook + setup: the tag flips $10.00 → $9.99, then the left digit takes over. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.intro}>
        <SafeArea>
          <Kicker text="Priced In" delay={2} />
          <Sequence durationInFrames={SETUP_AT} layout="none">
            <HookText lines={["Why is it always", "$9.99?"]} highlight={["$9.99"]} delay={4} />
          </Sequence>
          <Sequence from={SETUP_AT} layout="none">
            <HookText lines={["Your brain reads", "left to right."]} highlight={["left"]} delay={2} />
          </Sequence>
          <PriceTag from="10.00" to="9.99" delay={6} flipAt={16} focusLeftAt={SETUP_AT + 18} />
          <Sfx name="price-tag-roll" at={16} volume={0.6} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 3. Meme: my brain seeing $9.99 → Gus shrugs "basically $9". */}
      <TransitionSeries.Sequence durationInFrames={SCENES.meme}>
        <SafeArea>
          <HookText lines={["My brain", "seeing $9.99:"]} highlight={["$9.99"]} size={84} delay={6} />
          <Mascot pose="shrug" size={500} delay={16} poseAt={96} says="basically $9" saysHighlight={["$9"]} saysAt={102} />
          <Sfx name="pop" at={102} volume={0.45} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 4. Mechanism 1: the left-digit effect. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.versus}>
        <SafeArea>
          <HookText lines={["The left-digit", "effect"]} highlight={["left-digit"]} size={80} delay={6} />
          <VersusCard
            left={{ label: "Ten dollars", value: "$10.00" }}
            right={{ label: "One cent less", value: "$9.99", note: "feels like a $9 thing" }}
            delay={87}
          />
          {/* Click as the $9.99 card (right side, 18 frames after the left) lands. */}
          <Sfx name="mechanical-click" at={111} volume={0.45} />
          <HookText lines={["Real gap: 1¢"]} size={56} delay={125} />
          <SourceNote text="Source: Thomas & Morwitz, Journal of Consumer Research, 2005" delay={130} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 5. Mechanism 2: three places you see it. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.list}>
        <SafeArea>
          <HookText lines={["You'll see it", "everywhere."]} highlight={["everywhere"]} size={80} delay={6} />
          <ListReveal
            items={["Gas: priced to 9/10 of a cent", "Menus: $12.99, not $13", "Streaming: $14.99 a month"]}
            at={[44, 126, 160]}
          />
          <SourceNote text="Gas pricing: NACS" delay={60} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 6. Twist: luxury goes round. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.twist}>
        <SafeArea>
          <HookText lines={["Luxury does", "the opposite."]} highlight={["opposite"]} size={80} delay={6} />
          <VersusCard
            left={{ label: "Discount", value: "$9.99", note: "says “deal”" }}
            right={{ label: "Luxury", value: "$300", note: "says “no tricks”" }}
            delay={108}
          />
          <SourceNote text="Round prices & quality: Stiving, Management Science, 2000" delay={126} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 7. Payoff. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.payoff}>
        <SafeArea>
          <HookText lines={["One cent.", "That's the", "whole trick."]} highlight={["trick"]} delay={4} />
          <PriceTag from="10.00" to="9.99" size={110} delay={40} flipAt={50} />
          <Sfx name="price-tag-roll" at={50} volume={0.6} />
        </SafeArea>
      </TransitionSeries.Sequence>
    </TransitionSeries>

    <Audio src={staticFile("videos/why-999/voiceover.mp3")} volume={0.85} />
    <Audio src={staticFile("music/track-3-playful.mp3")} volume={musicVolume} />
    <AbsoluteFill>
      <Captions captions={captions} />
    </AbsoluteFill>
  </BrandedVideo>
);
