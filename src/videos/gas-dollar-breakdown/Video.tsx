/**
 * Gas is $4.10. Where does it go? (The Fine Print) — script and sources in ./script.md.
 * Scenes are timed to public/videos/gas-dollar-breakdown/voiceover.mp3 (Gemini TTS take,
 * 49.9 s; word timings in ./captions.json, aligned to the audio). If the voice-over is
 * replaced, re-time BEATS and the delays.
 */
import React from "react";
import { AbsoluteFill, getStaticFiles, interpolate, Sequence, staticFile } from "remotion";
import { Audio } from "@remotion/media";
import type { Caption } from "@remotion/captions";
import { linearTiming, TransitionSeries } from "@remotion/transitions";
import { slide } from "@remotion/transitions/slide";
import { sec, theme } from "../../brand";
import {
  BarChart,
  BrandBackground,
  BrandedVideo,
  Captions,
  CoinBuckets,
  coinBucketLandFrames,
  HookText,
  Kicker,
  ListReveal,
  Mascot,
  PumpCounter,
  SafeArea,
  SourceNote,
  StatCard,
} from "../../components";
import captionsJson from "./captions.json";

const SLUG = "gas-dollar-breakdown";
const VOICEOVER = `videos/${SLUG}/voiceover.mp3`;
const hasVoiceover = getStaticFiles().some((f) => f.name === VOICEOVER);

const T = theme.motion.transitionFrames;

// Beat starts (s), each just before its first word in the voice-over: hook, meme ("So where"),
// buckets ("About half"), jump ("Why the jump"), station ("And the station"), payoff ("The pump"), end.
// Voice-over runs 49.48 s; the end leaves ~0.55 s of breathing room.
const BEATS = [0, 3.6, 6.9, 24.3, 36.8, 45.9, 50.05];
const len = (i: number) => sec(BEATS[i + 1]) - sec(BEATS[i]);

const SCENES = {
  hook: len(0) + T,
  meme: len(1) + T,
  buckets: len(2) + T,
  jump: len(3) + T,
  station: len(4) + T,
  payoff: len(5),
};
const TRANSITIONS = Object.keys(SCENES).length - 1;

/** Content length without the end card. Registered in src/videos/index.ts. */
export const CONTENT_FRAMES = Object.values(SCENES).reduce((a, b) => a + b, 0) - TRANSITIONS * T;

// Word timings aligned to the voice-over (numbers written the way the screen shows them).
const captions: Caption[] = captionsJson;

const push = () => (
  <TransitionSeries.Transition
    presentation={slide({ direction: "from-right" })}
    timing={linearTiming({ durationInFrames: T })}
  />
);

/** One sound effect, starting `at` frames into its scene (public/sfx, generated by scripts/audio/sfx.mjs). */
const Sfx: React.FC<{ name: string; at: number; volume?: number }> = ({ name, at, volume = 0.5 }) => (
  <Sequence from={at} layout="none">
    <Audio src={staticFile(`sfx/${name}.mp3`)} volume={volume} />
  </Sequence>
);

/** Music bed: 0.12 under the voice, 15-frame fade in, 30-frame fade out before the end card. */
const musicVolume = (f: number) =>
  interpolate(f, [0, 15, CONTENT_FRAMES - 30, CONTENT_FRAMES], [0, 0.12, 0.12, 0], {
    extrapolateLeft: "clamp",
    extrapolateRight: "clamp",
  });

// One gallon at EIA's August 2026 split, applied to a $50 fill-up.
const BUCKETS = [
  { label: "Crude oil", amount: "$25", share: 0.5 },
  { label: "Refining", amount: "$12", share: 0.24 },
  { label: "Delivery & station", amount: "$6.50", share: 0.13 },
  { label: "Taxes", amount: "$6.50", share: 0.13 },
];
const BUCKET_AT = [45, 114, 219, 351]; // "crude", "quarter", "thirteen cents", "another thirteen"

/** Frame (scene-relative) in the jump scene where the explainer hands over to the chart. */
const CHART_AT = 222; // "and crude prices spiked"
/** Frame in the station scene where "The real money is inside" starts. */
const INSIDE_AT = 130; // "The real money"

export const GasDollarBreakdown: React.FC = () => (
  <BrandedVideo contentFrames={CONTENT_FRAMES}>
    <BrandBackground />
    <TransitionSeries>
      {/* 1. Hook: the number everyone saw this week. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.hook}>
        <SafeArea>
          <Kicker text="The Fine Print" delay={2} />
          <HookText lines={["Gas is $4.10.", "Where does it go?"]} highlight={["$4.10"]} delay={4} />
          <StatCard value={4.1} prefix="$" decimals={2} label="National average, regular" delay={24} countFrames={24} />
          <Sfx name="pump-click" at={46} volume={0.5} />
          <SourceNote text="Source: AAA national average, Nov 5, 2026" delay={34} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 2. Meme: me at the pump watching the numbers go up. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.meme}>
        <SafeArea>
          <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between" }}>
            <HookText lines={["Me at", "the pump:"]} size={84} delay={4} />
            <Mascot pose="nervous" size={240} delay={30} poseAt={40} />
          </div>
          <PumpCounter total={50} pricePerGallon={4.1} delay={6} startAt={14} countFrames={54} />
          <Sfx name="cash-counter-tick" at={14} volume={0.4} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 3. Mechanism 1: where a $50 fill-up goes, bucket by bucket. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.buckets}>
        <SafeArea>
          <HookText lines={["Where your $50 goes"]} highlight={["$50"]} size={72} delay={4} />
          <CoinBuckets buckets={BUCKETS} at={BUCKET_AT} highlight={0} delay={8} />
          <Sfx name="coin-drop-soft" at={BUCKET_AT[0] + coinBucketLandFrames(BUCKETS[0].share) - 6} volume={0.35} />
          <SourceNote text="Source: EIA, cost shares of a gallon of regular, Aug 2026" delay={20} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 4. Mechanism 2: why it jumped this year. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.jump}>
        <SafeArea>
          <Sequence durationInFrames={CHART_AT} layout="none">
            <HookText lines={["Why the jump?"]} highlight={["jump"]} size={88} delay={6} />
            <HookText lines={["Strait of Hormuz", "disrupted.", "Crude spiked."]} highlight={["Hormuz"]} size={72} delay={66} />
          </Sequence>
          <Sequence from={CHART_AT} layout="none">
            <BarChart
              title="Gas, national average"
              data={[
                { label: "Nov '25", value: 3.06, display: "$3.06" },
                { label: "May '26 peak", value: 4.56, display: "$4.56" },
                { label: "Now", value: 4.1, display: "$4.10" },
              ]}
              highlight={1}
              height={360}
              delay={2}
            />
            <Sfx name="mechanical-click" at={14} volume={0.45} />
            <SourceNote text="Source: AAA; CNBC, Jun 18, 2026" delay={20} />
          </Sequence>
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 5. Mechanism 3: the station makes its money inside. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.station}>
        <SafeArea>
          <Sequence durationInFrames={INSIDE_AT} layout="none">
            <HookText lines={["The station makes", "cents on gas."]} highlight={["cents"]} size={84} delay={6} />
            <Sfx name="pump-click" at={10} volume={0.45} />
          </Sequence>
          <Sequence from={INSIDE_AT} layout="none">
            <HookText lines={["The real money", "is inside."]} highlight={["inside"]} size={84} delay={2} />
            <ListReveal items={["Coffee", "Snacks", "Energy drinks"]} at={[62, 82, 109]} />
          </Sequence>
          <SourceNote text="Source: NACS, fuel margins & in-store sales" delay={20} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 6. Payoff. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.payoff}>
        <SafeArea>
          <HookText lines={["The pump is the", "last gear in a", "very long machine."]} highlight={["gear"]} delay={4} />
          <Sfx name="gear-ratchet" at={30} volume={0.45} />
        </SafeArea>
      </TransitionSeries.Sequence>
    </TransitionSeries>

    {hasVoiceover ? <Audio src={staticFile(VOICEOVER)} volume={0.85} /> : null}
    <Audio src={staticFile("music/track-2-tension.mp3")} volume={musicVolume} />
    <AbsoluteFill>
      <Captions captions={captions} />
    </AbsoluteFill>
  </BrandedVideo>
);
