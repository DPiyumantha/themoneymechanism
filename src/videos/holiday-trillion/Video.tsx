/**
 * Americans will spend $1 trillion this holiday (The Fine Print) — script and sources in ./script.md.
 * Scenes are timed to public/videos/holiday-trillion/voiceover.mp3 (Gemini TTS take, 38.3 s of
 * speech; word timings in ./captions.json, aligned to the audio). If the voice-over is replaced,
 * re-time BEATS and the delays.
 */
import React from "react";
import { AbsoluteFill, getStaticFiles, interpolate, Sequence, staticFile } from "remotion";
import { Audio } from "@remotion/media";
import type { Caption } from "@remotion/captions";
import { linearTiming, TransitionSeries } from "@remotion/transitions";
import { slide } from "@remotion/transitions/slide";
import { sec, theme } from "../../brand";
import {
  BarChart,
  BrandBackground,
  BrandedVideo,
  Captions,
  HookText,
  Kicker,
  Mascot,
  SafeArea,
  SourceNote,
  StatCard,
  VersusCard,
} from "../../components";
import captionsJson from "./captions.json";

const SLUG = "holiday-trillion";
const VOICEOVER = `videos/${SLUG}/voiceover.mp3`;
const hasVoiceover = getStaticFiles().some((f) => f.name === VOICEOVER);

const T = theme.motion.transitionFrames;

// Beat starts (s), each just before its first word: hook, forecast ("The National"), growth
// ("That's up"), catch ("But here's"), hiring ("And retailers"), payoff ("Same shopping"), end.
// Voice-over runs 38.3 s of speech; the end leaves ~1.2 s of breathing room.
const BEATS = [0, 4.5, 12.7, 18.0, 29.7, 35.3, 39.5];
const len = (i: number) => sec(BEATS[i + 1]) - sec(BEATS[i]);

const SCENES = {
  hook: len(0) + T,
  forecast: len(1) + T,
  growth: len(2) + T,
  catch: len(3) + T,
  hiring: len(4) + T,
  payoff: len(5),
};
const TRANSITIONS = Object.keys(SCENES).length - 1;

/** Content length without the end card. Registered in src/videos/index.ts. */
export const CONTENT_FRAMES = Object.values(SCENES).reduce((a, b) => a + b, 0) - TRANSITIONS * T;

// Word timings aligned to the voice-over (numbers written the way the screen shows them).
const captions: Caption[] = captionsJson;

const push = () => (
  <TransitionSeries.Transition
    presentation={slide({ direction: "from-right" })}
    timing={linearTiming({ durationInFrames: T })}
  />
);

/** One sound effect, starting `at` frames into its scene (public/sfx, generated by scripts/audio/sfx.mjs). */
const Sfx: React.FC<{ name: string; at: number; volume?: number }> = ({ name, at, volume = 0.5 }) => (
  <Sequence from={at} layout="none">
    <Audio src={staticFile(`sfx/${name}.mp3`)} volume={volume} />
  </Sequence>
);

/** Music bed: 0.12 under the voice, 15-frame fade in, 30-frame fade out before the end card. */
const musicVolume = (f: number) =>
  interpolate(f, [0, 15, CONTENT_FRAMES - 30, CONTENT_FRAMES], [0, 0.12, 0.12, 0], {
    extrapolateLeft: "clamp",
    extrapolateRight: "clamp",
  });

/** Frame (scene-relative) in the catch scene where "Gas, groceries…" starts and the meme takes over. */
const MEME_AT = sec(22.6 - 18.0); // "Gas,"

export const HolidayTrillion: React.FC = () => (
  <BrandedVideo contentFrames={CONTENT_FRAMES}>
    <BrandBackground />
    <TransitionSeries>
      {/* 1. Hook. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.hook}>
        <SafeArea>
          <Kicker text="The Fine Print" delay={2} />
          <HookText lines={["$1 trillion", "in two months."]} highlight={["trillion"]} delay={4} />
          <Sfx name="gear-ratchet" at={8} volume={0.4} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 2. The forecast. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.forecast}>
        <SafeArea align="center">
          <StatCard
            value={1.013}
            prefix="$"
            suffix="T"
            decimals={3}
            label="Forecast holiday sales, Nov–Dec"
            delay={6}
            countFrames={36}
          />
          <Sfx name="cash-counter-tick" at={8} volume={0.4} />
          <SourceNote text="Source: National Retail Federation, Oct 15, 2026" delay={36} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 3. Up 4.2% from last year. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.growth}>
        <SafeArea>
          <BarChart
            title="Holiday retail sales, Nov–Dec"
            data={[
              { label: "2025", value: 972, display: "$972B" },
              { label: "2026 est.", value: 1013, display: "$1.013T" },
            ]}
            highlight={1}
            height={420}
            delay={6}
          />
          <Sfx name="mechanical-click" at={30} volume={0.45} />
          <SourceNote text="Source: NRF, Oct 15, 2026 (+4.2%)" delay={30} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 4. The catch: part of it is just higher prices. Meme from "Gas, groceries…". */}
      <TransitionSeries.Sequence durationInFrames={SCENES.catch}>
        <SafeArea>
          <Sequence durationInFrames={MEME_AT} layout="none">
            <HookText lines={["Part of that", "is just", "higher prices."]} highlight={["prices."]} delay={4} />
          </Sequence>
          <Sequence from={MEME_AT} layout="none">
            <HookText
              lines={["My bank account", "watching me start", "holiday shopping", "in November:"]}
              size={64}
              delay={4}
            />
            <div style={{ display: "flex", justifyContent: "center", marginTop: 40 }}>
              <Mascot pose="nervous" size={380} delay={20} poseAt={34} />
            </div>
            <Sfx name="pop" at={22} volume={0.4} />
          </Sequence>
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 5. Retailers are cautious. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.hiring}>
        <SafeArea>
          <HookText lines={["Seasonal hiring:", "about the same."]} highlight={["same."]} size={76} delay={4} />
          <VersusCard
            left={{ label: "Last year", value: "~356k", note: "seasonal hires" }}
            right={{ label: "2026 plan", value: "325k–375k", note: "seasonal hires" }}
            emphasis="right"
            delay={40}
          />
          <Sfx name="mechanical-click" at={46} volume={0.45} />
          <SourceNote text="Source: NRF, Oct 15, 2026" delay={60} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 6. Payoff. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.payoff}>
        <SafeArea>
          <HookText lines={["Same shopping.", "Bigger number."]} highlight={["Bigger"]} delay={4} />
          <Sfx name="gear-ratchet" at={30} volume={0.45} />
        </SafeArea>
      </TransitionSeries.Sequence>
    </TransitionSeries>

    {hasVoiceover ? <Audio src={staticFile(VOICEOVER)} volume={0.85} /> : null}
    <Audio src={staticFile("music/track-1-gold-standard.mp3")} volume={musicVolume} />
    <AbsoluteFill>
      <Captions captions={captions} />
    </AbsoluteFill>
  </BrandedVideo>
);
