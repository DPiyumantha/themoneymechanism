/**
 * Costco barely profits on groceries. (Follow the Money) — script and sources in ./script.md.
 * Timed to the Gemini voice-over (public/videos/costco-memberships/voiceover.mp3, 44.6 s;
 * word timings in ./captions.json, aligned to the audio). The voice-over plays in two parts
 * with a GAP-second pause before the payoff, so the fee chart has time on screen. If the
 * voice-over is replaced, re-align the captions and re-time BEATS, GAP and the in-scene delays.
 * The warehouse photo shows only once public/videos/costco-memberships/warehouse.jpg exists.
 */
import React from "react";
import { AbsoluteFill, getStaticFiles, interpolate, Sequence, staticFile } from "remotion";
import { Audio } from "@remotion/media";
import type { Caption } from "@remotion/captions";
import { linearTiming, TransitionSeries } from "@remotion/transitions";
import { slide } from "@remotion/transitions/slide";
import { sec, theme } from "../../brand";
import {
  BarChart,
  BrandBackground,
  BrandedVideo,
  Captions,
  ExpectationReality,
  HookText,
  Kicker,
  ListReveal,
  MemberCard,
  PhotoFrame,
  SafeArea,
  SourceNote,
  VersusCard,
} from "../../components";
import captionsJson from "./captions.json";

const SLUG = "costco-memberships";
const VOICEOVER = `videos/${SLUG}/voiceover.mp3`;
const PHOTO = `videos/${SLUG}/warehouse.jpg`;
const files = getStaticFiles();
const hasVoiceover = files.some((f) => f.name === VOICEOVER);
const hasPhoto = files.some((f) => f.name === PHOTO);

const T = theme.motion.transitionFrames;

// Voice-over split: everything after GAP_AT s (between "come back." and "You're not")
// plays GAP s later, giving the chart scene a beat before the payoff.
const GAP_AT = 41.3;
const GAP = 1.2;

// Beat starts (s, video time): hook, setup ("Costco keeps"), card ("So where"),
// versus ("Membership fees"), list ("And it works"), meme ("Costco doesn't"),
// chart ("It needs you"), payoff ("You're not", after the gap), end.
const BEATS = [0, 3.95, 8.5, 12.9, 23.6, 36.45, 39.4, 42.6, 46.4];
const len = (i: number) => sec(BEATS[i + 1]) - sec(BEATS[i]);

const SCENES = {
  hook: len(0) + T,
  setup: len(1) + T,
  card: len(2) + T,
  versus: len(3) + T,
  list: len(4) + T,
  meme: len(5) + T,
  chart: len(6) + T,
  payoff: len(7),
};
const TRANSITIONS = Object.keys(SCENES).length - 1;

/** Content length without the end card. Registered in src/videos/index.ts. */
export const CONTENT_FRAMES = Object.values(SCENES).reduce((a, b) => a + b, 0) - TRANSITIONS * T;

const captions: Caption[] = captionsJson;

const push = () => (
  <TransitionSeries.Transition
    presentation={slide({ direction: "from-right" })}
    timing={linearTiming({ durationInFrames: T })}
  />
);

/** One sound effect, starting `at` frames into its scene (public/sfx, generated by scripts/audio/sfx.mjs). */
const Sfx: React.FC<{ name: string; at: number; volume?: number }> = ({ name, at, volume = 0.5 }) => (
  <Sequence from={at} layout="none">
    <Audio src={staticFile(`sfx/${name}.mp3`)} volume={volume} />
  </Sequence>
);

/** Music bed: 0.12 under the voice, 15-frame fade in, 30-frame fade out before the end card. */
const musicVolume = (f: number) =>
  interpolate(f, [0, 15, CONTENT_FRAMES - 30, CONTENT_FRAMES], [0, 0.12, 0.12, 0], {
    extrapolateLeft: "clamp",
    extrapolateRight: "clamp",
  });

/** Frame (scene-relative) the two VersusCard figures start landing. */
const VERSUS_AT = 51;

export const CostcoMemberships: React.FC = () => (
  <BrandedVideo contentFrames={CONTENT_FRAMES}>
    <BrandBackground />
    <TransitionSeries>
      {/* 1. Hook. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.hook}>
        <SafeArea>
          <Kicker text="Follow the Money" delay={2} />
          <HookText lines={["Costco barely", "profits on", "groceries."]} highlight={["barely"]} delay={4} />
          <HookText lines={["Seriously."]} size={64} delay={84} />
          <Sfx name="pop" at={84} volume={0.4} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 2. Setup: what you think it sells. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.setup}>
        <SafeArea>
          <HookText lines={["Low markups on", "almost everything."]} highlight={["low"]} size={84} delay={6} />
          {hasPhoto ? <PhotoFrame src={staticFile(PHOTO)} aspect={1.9} delay={10} /> : null}
          <SourceNote text="Source: Costco FY2026 Form 10-K" delay={24} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 3. The turn: the card in your wallet is the engine. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.card}>
        <SafeArea>
          <HookText lines={["So where's", "the profit?"]} highlight={["profit"]} size={84} delay={6} />
          <MemberCard delay={8} slideAt={84} gearAt={104} />
          <Sfx name="gear-ratchet" at={104} volume={0.45} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 4. Mechanism 1: membership fees vs total profit. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.versus}>
        <SafeArea>
          <HookText lines={["The card pays", "the bills."]} highlight={["card"]} size={80} delay={6} />
          <VersusCard
            left={{ label: "Net income", value: "$9.2B" }}
            right={{ label: "Membership fees", value: "$5.9B" }}
            delay={VERSUS_AT}
          />
          <Sfx name="mechanical-click" at={VERSUS_AT + 18} volume={0.45} />
          <HookText lines={["≈ 2/3 of net income"]} highlight={["2/3"]} size={56} delay={268} />
          <SourceNote text="Source: Costco FY2026 Form 10-K (52 weeks to Aug 30, 2026)" delay={VERSUS_AT + 24} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 5. Mechanism 2: the three gears. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.list}>
        <SafeArea>
          <HookText lines={["It runs on", "three gears."]} highlight={["gears"]} size={80} delay={6} />
          <ListReveal
            items={["You pay up front", "You shop more to make it pay", "92.3% renew (US & Canada)"]}
            at={[94, 193, 278]}
          />
          <Sfx name="mechanical-click" at={278} volume={0.45} />
          <SourceNote text="Renewal rate: Costco FY2026 Form 10-K" delay={286} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 6. Meme: expectation vs reality. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.meme}>
        <SafeArea>
          <ExpectationReality expectation="I'll just grab milk." reality="Me, an hour later." delay={2} realityAt={40} />
          <Sfx name="record-scratch" at={38} volume={0.4} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 7. Mechanism 3: members come back, so the fees keep growing. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.chart}>
        <SafeArea>
          <BarChart
            title="Membership fees by year"
            data={[
              { label: "FY22", value: 4.224, display: "$4.2B" },
              { label: "FY23", value: 4.58, display: "$4.6B" },
              { label: "FY24", value: 4.828, display: "$4.8B" },
              { label: "FY25", value: 5.323, display: "$5.3B" },
              { label: "FY26", value: 5.907, display: "$5.9B" },
            ]}
            height={380}
            delay={2}
          />
          <Sfx name="cash-counter-tick" at={4} volume={0.35} />
          <SourceNote text="Source: Costco Form 10-K filings, FY2022–FY2026" delay={16} />
        </SafeArea>
      </TransitionSeries.Sequence>
      {push()}

      {/* 8. Payoff. */}
      <TransitionSeries.Sequence durationInFrames={SCENES.payoff}>
        <SafeArea>
          <HookText lines={["You're not", "the customer."]} delay={4} />
          <HookText lines={["You're the", "subscriber."]} highlight={["subscriber"]} delay={54} />
          <Sfx name="mechanical-click" at={66} volume={0.45} />
        </SafeArea>
      </TransitionSeries.Sequence>
    </TransitionSeries>

    {hasVoiceover ? (
      <>
        <Audio src={staticFile(VOICEOVER)} volume={0.85} trimAfter={sec(GAP_AT)} />
        <Sequence from={sec(GAP_AT + GAP)} layout="none">
          <Audio src={staticFile(VOICEOVER)} volume={0.85} trimBefore={sec(GAP_AT)} />
        </Sequence>
      </>
    ) : null}
    <Audio src={staticFile("music/track-1-gold-standard.mp3")} volume={musicVolume} />
    <AbsoluteFill>
      <Captions captions={captions} />
    </AbsoluteFill>
  </BrandedVideo>
);
